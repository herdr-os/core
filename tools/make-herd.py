#!/usr/bin/env python3
"""Builds the herd from design-reference/harnesses.json, the one list of harnesses Herdr OS knows.

Writes, for every harness:
  design-reference/sheep/brand-<id>.svg and -sleep.svg   (skipped for "drawn" ones, drawn by hand)
  design-reference/harness-logos/<id>.svg                (lettermark, for harnesses with no published mark)
  app/src/main/res/values/harness_colors.xml
  app/src/main/java/dev/r1ptt/herdr/ui/Harness.kt
  site/public/sheep/brand-<id>*.svg and site/src/harnesses.json
Then run tools/render-sheep.sh for the app's PNGs.
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "design-reference"
HARNESSES = json.loads((REF / "harnesses.json").read_text())


def rgb(hex_):
    return [int(hex_[i:i + 2], 16) for i in (1, 3, 5)]


def shade(hex_, f):
    """f > 0 mixes toward white, f < 0 toward black."""
    return "#" + "".join(f"{round(c + (255 - c) * f if f > 0 else c * (1 + f)):02X}" for c in rgb(hex_))


def dark(hex_):
    r, g, b = (c / 255 for c in rgb(hex_))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b < 0.4


def logo_mark(h):
    """The harness logo as one-color SVG content fitted into the 24-unit box the sheep's back expects."""
    if "mark" in h:
        return f'<text x="12" y="19.5" text-anchor="middle" font-family="Helvetica, Arial, sans-serif" font-weight="800" font-size="22" fill="{h["ink"]}">{h["mark"]}</text>'
    svg = (REF / "harness-logos" / f"{h.get('logo', h['id'])}.svg").read_text()
    vb = re.search(r'viewBox="([^"]+)"', svg)
    x, y, w, hh = map(float, vb[1].split()) if vb else (0, 0, float(re.search(r'width="([\d.]+)', svg)[1]), float(re.search(r'height="([\d.]+)', svg)[1]))
    inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg.strip(), flags=re.S)
    inner = re.sub(r'(fill|stroke)="(?!none)[^"]*"', rf'\1="{h["ink"]}"', inner)
    s = 24 / max(w, hh)
    tx, ty = -x * s + (24 - w * s) / 2, -y * s + (24 - hh * s) / 2
    return f'<g transform="translate({tx:.3f},{ty:.3f}) scale({s:.5f})" fill="{h["ink"]}">{inner}</g>'


def sheep(h, asleep):
    c = h["color"]
    back = [shade(c, .25), c, shade(c, -.2)]
    head = [shade(c, .3), shade(c, .06), shade(c, -.12)]
    face, eye = ("#F1ECEC", "#131010") if dark(c) else ("#0A0A0A", "#FFFFFF")
    block = lambda d, fill: f'<path d="{d}" fill="{fill}" stroke="{fill}" stroke-width="1.6" stroke-linejoin="round"/>'
    leg = lambda x, y, light: f'<path d="M{x},{y} L{x+3},{y+1.5} L{x+3},{y+8} L{x},{y+6.5} Z" fill="{light}"/><path d="M{x},{y+4.5} L{x+3},{y+6} L{x+3},{y+8} L{x},{y+6.5} Z" fill="#FF4A00"/>'
    eye_mark = (f'<path d="M6.3,28.2 L9,29.6" stroke="{eye}" stroke-width="1.1" stroke-linecap="round" fill="none"/>' if asleep
                else f'<path d="M7.6,28.6 m-1.1,0 a1.1,1.1 0,1 1,2.2 0 a1.1,1.1 0,1 1,-2.2 0" fill="{eye}"/>')
    return "".join([
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48">',
        leg(27, 32, "#D8D4CC"), leg(33, 29, "#D8D4CC"),
        block("M21,9 L39,18 L30,22.5 L12,13.5 Z", back[0]),
        block("M12,13.5 L30,22.5 L30,33 L12,24 Z", back[1]),
        block("M30,22.5 L39,18 L39,28.5 L30,33 Z", back[2]),
        f'<g transform="matrix(0.41250,0.20625,-0.20625,0.10313,23.0250,12.0375)">{logo_mark(h)}</g>',
        leg(7, 36, "#E7E3DC"), leg(15, 38.5, "#D3CEC5"),
        block("M3,21 L10,17.5 L23,24 L16,27.5 Z", head[0]),
        block("M3,21 L16,27.5 L16,39.5 L3,33 Z", head[1]),
        block("M16,27.5 L23,24 L23,36 L16,39.5 Z", head[2]),
        f'<path d="M4.6,24.6 L14.4,29.5 L14.4,36.4 L4.6,31.5 Z" fill="{face}" stroke="{face}" stroke-width="1.2" stroke-linejoin="round"/>',
        eye_mark,
        '<path d="M10.6,32.4 L12.8,33.5 M11.7,31.4 L11.7,34.6" fill="none" stroke="#FF4A00" stroke-width="1" stroke-linejoin="round"/>',
        '<path d="M20.5,28.6 L24.5,30.6 L24.5,34 L20.5,32 Z" fill="#1A1A1A" stroke="#1A1A1A" stroke-width="1.2" stroke-linejoin="round"/>',
        "</svg>",
    ])


def kotlin():
    const = lambda h: h["id"].upper()
    rows = ",\n".join(
        f'    {const(h)}("{h["label"]}", R.color.herd_{h["id"]}, R.color.herd_{h["id"]}_ink, R.drawable.sheep_brand_{h["id"]}, R.drawable.sheep_brand_{h["id"]}_sleep, R.drawable.logo_{h["id"]})'
        for h in HARNESSES)
    cases = "\n".join(f'            {", ".join(json.dumps(k) for k in h["kinds"])} -> {const(h)}' for h in HARNESSES)
    return f'''package dev.r1ptt.herdr.ui

import dev.r1ptt.R

// Generated by tools/make-herd.py from design-reference/harnesses.json; edit the table, not this file.

/**
 * Which coding tool an agent runs, and how the herd draws it: its brand color, the ink that reads
 * on that color, and its sheep. Color names the harness only; state is always written out.
 */
enum class Harness(
    val label: String,
    val color: Int,
    val ink: Int,
    val sheep: Int,
    val asleep: Int,
    val logo: Int,
) {{
{rows},
    OTHER("Agent", R.color.herd_other, R.color.herd_other_ink, R.drawable.sheep_plain, R.drawable.sheep_plain_sleep, R.drawable.herdr_sheep);

    companion object {{
        /** Herdr's agent kind (`herdr agent start --kind`) to its harness. */
        fun of(kind: String): Harness = when (kind.lowercase()) {{
{cases}
            else -> OTHER
        }}
    }}
}}
'''


def main():
    sheep_dir, logos = REF / "sheep", REF / "harness-logos"
    for h in HARNESSES:
        if "mark" in h:
            (logos / f"{h['id']}.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">{logo_mark(h)}</svg>')
        if not h.get("drawn"):
            (sheep_dir / f"brand-{h['id']}.svg").write_text(sheep(h, False))
            (sheep_dir / f"brand-{h['id']}-sleep.svg").write_text(sheep(h, True))
    colors = "\n".join(f'    <color name="herd_{h["id"]}">{h["color"]}</color>\n    <color name="herd_{h["id"]}_ink">{h["ink"]}</color>' for h in HARNESSES)
    (ROOT / "app/src/main/res/values/harness_colors.xml").write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make-herd.py from design-reference/harnesses.json. -->\n<resources>\n{colors}\n</resources>\n')
    (ROOT / "app/src/main/java/dev/r1ptt/herdr/ui/Harness.kt").write_text(kotlin())
    site = ROOT / "site/public/sheep"
    for f in sheep_dir.glob("*.svg"):
        shutil.copy(f, site / f.name)
    # The website is also published from a copy of site/ alone, so it carries its own copy of the table.
    shutil.copy(REF / "harnesses.json", ROOT / "site/src/harnesses.json")
    print(f"{len(HARNESSES)} harnesses")


main()
